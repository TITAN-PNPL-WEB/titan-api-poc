package poc.titan.api.logging;

import jakarta.annotation.PreDestroy;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;
import org.springframework.web.servlet.mvc.method.annotation.SseEmitter;
import poc.titan.api.dto.LogEvent;

import java.time.Duration;
import java.time.Instant;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.regex.Pattern;

/**
 * Keeps the recent log events of each front-end session and streams them live with Server-Sent Events.
 *
 * A session is identified by a UUID generated by the front end. Requests that carry it in the
 * X-Log-Session header (see LogSessionFilter) have their logs, including the TITAN core output,
 * stored here and sent to every stream open on GET /pnpl/logs/{sessionId}.
 *
 * Events are sent by a single dispatcher thread, so a slow client never blocks an analysis, and
 * every stream receives its events in order, without gaps or duplicates while they are buffered.
 * This class must not log while publishing: its own logs would be published again.
 */
@Service
public class LogStreamService {

    /** MDC key holding the session of the current request. */
    public static final String MDC_KEY = "logSession";

    private static final Pattern SESSION_ID = Pattern.compile(
            "[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}");

    private final int bufferSize;
    private final int maxSessions;
    private final Duration sessionTtl;
    private final Duration streamTimeout;
    private final Map<String, LogSession> sessions = new ConcurrentHashMap<>();
    private final ExecutorService dispatcher = Executors.newSingleThreadExecutor(r -> {
        Thread t = new Thread(r, "log-stream");
        t.setDaemon(true);
        return t;
    });

    public LogStreamService(@Value("${titan.logs.buffer-size:2000}") int bufferSize,
                            @Value("${titan.logs.max-sessions:200}") int maxSessions,
                            @Value("${titan.logs.session-ttl:30m}") Duration sessionTtl,
                            @Value("${titan.logs.stream-timeout:30m}") Duration streamTimeout) {
        this.bufferSize = bufferSize;
        this.maxSessions = maxSessions;
        this.sessionTtl = sessionTtl;
        this.streamTimeout = streamTimeout;
    }

    /**
     * True if the id has the UUID format expected for a session.
     */
    public static boolean isValidSessionId(String id) {
        return id != null && SESSION_ID.matcher(id).matches();
    }

    /**
     * Stores an event in the session and schedules its delivery. Never blocks on the network.
     * Dropped silently if the maximum number of sessions is reached.
     */
    public void publish(String sessionId, Instant timestamp, String level, String source, String message) {
        LogSession session = session(sessionId);
        if (session == null) return;
        session.append(timestamp, level, source, message);
        scheduleFlush(session);
    }

    /**
     * Opens a stream on the session: first the buffered events after lastEventId, then the new ones live.
     */
    public SseEmitter subscribe(String sessionId, long lastEventId) {
        LogSession session = session(sessionId);
        if (session == null) {
            throw new ResponseStatusException(HttpStatus.SERVICE_UNAVAILABLE, "Too many open log sessions");
        }

        // An id beyond the session comes from before a server restart: the client gets everything again
        long from = lastEventId > session.lastSeq() ? 0 : lastEventId;
        SseEmitter emitter = new SseEmitter(streamTimeout.toMillis());
        LogSession.Subscriber subscriber = new LogSession.Subscriber(emitter, from);
        Runnable remove = () -> {
            session.subscribers.remove(subscriber);
            session.touch();
        };
        emitter.onCompletion(remove);
        emitter.onTimeout(remove);
        emitter.onError(e -> remove.run());

        session.subscribers.add(subscriber);
        session.touch();
        // Commits the response headers right away, so the client knows the stream is open before the first event
        dispatcher.execute(() -> {
            try {
                emitter.send(SseEmitter.event().comment("connected"));
            } catch (Exception e) {
                drop(session, subscriber);
            }
        });
        scheduleFlush(session);
        return emitter;
    }

    /**
     * Sends a comment to every stream, so proxies do not close idle connections and dead clients are detected.
     */
    @Scheduled(fixedRateString = "${titan.logs.heartbeat:15s}")
    public void heartbeat() {
        dispatcher.execute(() -> sessions.values().forEach(session -> {
            for (LogSession.Subscriber subscriber : session.subscribers) {
                try {
                    subscriber.emitter.send(SseEmitter.event().comment("keepalive"));
                } catch (Exception e) {
                    drop(session, subscriber);
                }
            }
        }));
    }

    /**
     * Removes the sessions with no open stream and no activity for longer than the session TTL.
     */
    @Scheduled(fixedRate = 60_000)
    public void evictIdleSessions() {
        Instant limit = Instant.now().minus(sessionTtl);
        sessions.values().removeIf(s -> s.subscribers.isEmpty() && s.lastActivity().isBefore(limit));
    }

    @PreDestroy
    public void shutdown() {
        dispatcher.shutdownNow();
        sessions.values().forEach(s -> s.subscribers.forEach(sub -> sub.emitter.complete()));
        sessions.clear();
    }

    private LogSession session(String sessionId) {
        LogSession session = sessions.get(sessionId);
        if (session != null) return session;
        if (sessions.size() >= maxSessions) return null;
        return sessions.computeIfAbsent(sessionId, id -> new LogSession(bufferSize));
    }

    // Coalesces the deliveries: at most one pending flush per session
    private void scheduleFlush(LogSession session) {
        if (session.flushScheduled.compareAndSet(false, true)) {
            dispatcher.execute(() -> flush(session));
        }
    }

    // Runs on the dispatcher thread: sends each stream the events it has not received yet
    private void flush(LogSession session) {
        session.flushScheduled.set(false);
        for (LogSession.Subscriber subscriber : session.subscribers) {
            for (LogEvent event : session.eventsAfter(subscriber.lastSent)) {
                try {
                    subscriber.emitter.send(SseEmitter.event()
                            .id(Long.toString(event.seq()))
                            .name("log")
                            .data(event, MediaType.APPLICATION_JSON));
                    subscriber.lastSent = event.seq();
                } catch (Exception e) {
                    drop(session, subscriber);
                    break;
                }
            }
        }
    }

    private static void drop(LogSession session, LogSession.Subscriber subscriber) {
        session.subscribers.remove(subscriber);
        try {
            subscriber.emitter.complete();
        } catch (Exception ignored) {
            // the connection is already gone
        }
    }
}
